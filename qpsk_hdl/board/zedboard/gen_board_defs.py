"""
Constants for the ZedBoard loopback demo, emitted as rtl/board_defs.vh.

The on-chip channel uses the same definitions as the Python channel model
(qpsk_float.channel): fo in turns per symbol, and Eb/N0 with
Es = mean|x|^2 * SPS, Eb = Es/2, N0 the complex noise variance per sample.
The signal power is measured on the bit exact transmitter model, so the
noise levels are calibrated to what the RTL transmitter actually produces.
"""

import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'model'))
import qpsk_params as P     # noqa: E402
import qpsk_fixed as Q      # noqa: E402

# The core RTL forms each filter output and loop update in a single clock
# (the matched filter is a 21-deep DSP cascade, ~38 ns on a -1 part), so the
# design clock is brought down from the board's 100 MHz to 20 MHz by an MMCM.
CLKS_PER_SAMPLE = 16        # 20 MHz / 16 = 1.25 MS/s, 312.5 kBd

# channel switch settings
FO_TABLE    = [0.0, 0.02, -0.04, 0.06]      # sw[1:0], turns per symbol
EBN0_TABLE  = [None, 10.0, 8.0, 6.0]        # sw[3:2], None = noise off
PHASE_DEG   = 37.0                          # sw[5:4] add multiples of 90

# LED BER bar: errors counted over windows of 2**BAR_BITS bits
BAR_BITS    = 18            # ~0.44 s at the 595 kbit/s payload rate

# The transmitter output peaks at about 0.91 of full scale per rail.  It is
# attenuated by 2**BASE_SHIFT before rotation so that rotation plus noise at
# the lowest Eb/N0 stays clear of saturation.
BASE_SHIFT  = 2

# awgn_gen: each rail is a sum of NUNIF signed 16 bit uniforms
NUNIF       = 16
NOISE_SHIFT = 16            # noise = (g * sigma_code) >> NOISE_SHIFT


def signal_power():
    """Mean |x|^2 of the transmitter output, full scale = 1."""
    rng = np.random.default_rng(1)
    npkt = 8
    bits = rng.integers(0, 2, npkt * P.DATA_BITS)
    _, samp = Q.tx(bits, npkt)
    x = np.array(samp, dtype=float) / float(1 << P.FRAC)
    x = x[100:]                                     # skip filter fill
    return float(np.mean(x[:, 0] ** 2 + x[:, 1] ** 2))


def main():
    p_tx = signal_power()
    p = p_tx / 4 ** BASE_SHIFT                      # after attenuation
    es = p * P.SPS
    eb = es / 2

    sigma_unif = np.sqrt(NUNIF * (2.0 ** 32) / 12.0)  # std of the uniform sum

    lines = []
    w = lines.append
    w('// ------------------------------------------------------------------------')
    w('// board_defs.vh - generated by board/zedboard/gen_board_defs.py.  Do not edit.')
    w('// ------------------------------------------------------------------------')
    w('localparam integer CLKS_PER_SAMPLE = %d;' % CLKS_PER_SAMPLE)
    w('localparam integer BASE_SHIFT      = %d;' % BASE_SHIFT)
    w('localparam integer NOISE_SHIFT     = %d;' % NOISE_SHIFT)
    w('')
    w('// transmitter mean power %.4f, after attenuation %.5f' % (p_tx, p))
    w('')
    w('// carrier frequency offset, phase increment per sample (2**32 = 1 turn)')
    for k, fo in enumerate(FO_TABLE):
        inc = int(round(fo / P.SPS * 2 ** 32)) & 0xFFFFFFFF
        w('localparam [31:0] FO_INC_%d = 32\'h%08X;   // %+.3f turns/symbol'
          % (k, inc, fo))
    w('')
    ph = int(round(PHASE_DEG / 360.0 * 65536)) & 0xFFFF
    w('localparam [15:0] PHASE_OFF = 16\'h%04X;   // %.0f degrees' % (ph, PHASE_DEG))
    w('')
    w('// noise standard deviation per rail, as a multiplier on the uniform sum')
    for k, e in enumerate(EBN0_TABLE):
        if e is None:
            w('localparam [15:0] SIGMA_%d = %-12s// noise off' % (k, "16'd0;"))
            continue
        n0 = eb / 10 ** (e / 10)
        sigma = np.sqrt(n0 / 2) * (1 << P.FRAC)       # LSBs per rail
        code = int(round(sigma * 2 ** NOISE_SHIFT / sigma_unif))
        assert 0 < code < 65536
        w('localparam [15:0] SIGMA_%d = %-12s// Eb/N0 %4.1f dB, %.0f LSB rms'
          % (k, "16'd%d;" % code, e, sigma))
    w('')
    w('// LED BER bar: error count thresholds per window of 2**BAR_BITS bits')
    w('localparam integer BAR_BITS = %d;' % BAR_BITS)
    for name, ber in (('BAR_1E4', 1e-4), ('BAR_1E3', 1e-3), ('BAR_1E2', 1e-2)):
        w('localparam [31:0] %s  = 32\'d%d;' % (name, round(ber * 2 ** BAR_BITS)))

    out = os.path.join(HERE, 'rtl', 'board_defs.vh')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('board_defs.vh written  (tx power %.4f)' % p_tx)


if __name__ == '__main__':
    main()
